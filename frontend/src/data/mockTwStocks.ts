function makeHolding(params: {
  id: string;
  stock: TwStockCandidate;
  valuationProfile: ValuationProfile;
  shares: number;
  costPrice: number;
  currentPrice: number;
  highestPriceSinceEntry: number;
  daysBelow200Ma: number;
  sQ: number;
  sV: number;
  sM: number;
  moatPermanentlyBroken?: boolean;
}): HoldingPosition {
  const sz = evaluateStageZero(params.stock.stageZeroInput, params.valuationProfile);
  const breakdown = { sQ: params.sQ, sV: params.sV, sM: params.sM };
  const rating = evaluateRating({ breakdown, regime: 'NORMAL', stageZero: sz });
  const cycRating =
    params.valuationProfile === 'cyclical_heavy_asset' ||
    params.valuationProfile === 'cyclical_inventory_order'
      ? evaluateCyclicalRating({
          profile: params.valuationProfile,
          regime: 'NORMAL',
          stageZero: sz,
          metrics: params.stock.cyclicalMetrics,
          price: params.currentPrice,
          ma120: params.stock.ma120,
          ma200: params.stock.ma200,
          rev3mCumYoYPct: params.stock.rev3mCumYoYPct,
          rev12mCumYoYPct: params.stock.rev12mCumYoYPct,
        })
      : undefined;

  const finRating =
    (params.valuationProfile === 'financial_bank' ||
      params.valuationProfile === 'financial_life_fhc') &&
    params.stock.financialMetrics
      ? evaluateFinancialRating({
          profile: params.valuationProfile,
          regime: 'NORMAL',
          commonStageZeroInput: params.stock.stageZeroInput,
          metrics: params.stock.financialMetrics,
          price: params.currentPrice,
          ma200: params.stock.ma200,
        })
      : undefined;

  return {
    id: params.id,
    symbol: params.stock.symbol,
    name: params.stock.name,
    sector: params.stock.sector,
    valuationProfile: params.valuationProfile,
    shares: params.shares,
    costPrice: params.costPrice,
    currentPrice: params.currentPrice,
    highestPriceSinceEntry: params.highestPriceSinceEntry,
    atr20: params.stock.atr20,
    ma60: params.stock.ma50,
    ma120: params.stock.ma120,
    ma200: params.stock.ma200,
    daysBelow200Ma: params.daysBelow200Ma,
    moatPermanentlyBroken: Boolean(params.moatPermanentlyBroken),
    stopDrawdownThresholdPct: 15,
    currentRating: rating,
    currentBreakdown: breakdown,
    cyclicalMetrics: params.stock.cyclicalMetrics,
    cyclicalRating: cycRating,
    financialMetrics: params.stock.financialMetrics,
    financialRating: finRating,
  };
}

